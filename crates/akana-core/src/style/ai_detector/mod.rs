//! Trained Turkish AI-generated-text detector, used by the style auditor
//! ([`super::TurkishStyleAuditor::audit`] fills [`super::StyleAuditReport::ai_detection`]) and
//! the humanizer ([`super::TurkishHumanizer::format_prompt`]).
//!
//! **The output is not proof of authorship.** It is a calibrated probability from 500
//! gradient-boosted trees trained on OpenAI and Claude answers versus Turkish human text
//! written before November 2022. On a held-out OpenAI evaluation set, at a threshold giving
//! 1% false alarms on separate human texts, it flagged about 95 of 100 AI texts it judged
//! (texts with 65+ words). Poems get no decision, academic text a warning, and shorter or
//! highly repetitive texts are not judged.
//!
//! The trees read 75 numbers:
//!
//! 1. 68 content statistics ([`features`]) of the cleaned text ([`preprocess()`]);
//! 2. 5 counts of mined AI patterns ([`patterns`]) on the raw text;
//! 3. 2 token-transition scores ([`tokens`]) over Akana's embedding tokenizer.
//!
//! Every helper here is frozen to the definitions the model was trained with, including its
//! own copy of the cliché patterns ([`cliches`]), so the auditor's rules can evolve on their
//! own. Changing a word or sentence splitter, the cleaning, a word list or the shared code it
//! calls ([`crate::tokenization::SentenceSegmenter`], [`crate::phonology::alphabet`], the
//! Zemberek lexicon, the Ateşman formula, the embedding tokenizer) changes the model's inputs:
//! the test `outputs_match_training_reference` pins every input on a committed sample
//! (`tests/data/ai_detector_reference.json`).
//!
//! The embedded data (`data/ai_detector/model.json`, `data/ai_detector/tokens.bin.zz`, formats
//! in [`model`] and [`tokens`]) is generated by the detector's training code, kept in a
//! outside this repository together with its evaluation data. Training data: AI answers
//! from OpenAI and Claude models (WildChat, LMArena and other conversation datasets) and Turkish
//! human text written before November 2022 (forums including FineWeb-2, Ekşi Sözlük); the
//! embedded files hold only aggregate statistics, no training text.

