/// Different words a text needs for a decision: repetitive input ("bir bir bir …") is
/// outside what the model was trained on.
const MIN_DISTINCT_WORDS: usize = 20;
/// Inputs kept in [`AiDetection::signals`] (largest absolute contribution first).
const MAX_SIGNALS: usize = 20;
/// Sliding sections: length and step in words; texts shorter than `SECTION_MIN_WORDS`
/// get none.
const SECTION_WORDS: usize = 80;
const SECTION_STEP: usize = 40;
const SECTION_MIN_WORDS: usize = 120;
/// Lengths of the report's lists.
const REPORT_AI_SIGNALS: usize = 6;
const REPORT_HUMAN_SIGNALS: usize = 3;
const REPORT_PATTERNS: usize = 10;

/// Decision of the detector.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum AiVerdict {
    /// Probability at or above the flag threshold.
    Ai,
    /// Between the human cut-off and the flag threshold.
    Uncertain,
    /// Below the human cut-off.
    Human,
    /// Fewer content words than the model's minimum: no decision.
    TooShort,
    /// A poem: no decision (see [`ScopeWarning`]).
    OutOfScope,
}

impl AiVerdict {
    /// Turkish label.
    pub fn label_tr(self) -> &'static str {
        match self {
            Self::Ai => "AI",
            Self::Uncertain => "emin değil",
            Self::Human => "insan",
            Self::TooShort => "çok kısa",
            Self::OutOfScope => "kapsam dışı",
        }
    }

    /// Whether the detector made a decision (AI, uncertain or human).
    pub fn is_decided(self) -> bool {
        matches!(self, Self::Ai | Self::Uncertain | Self::Human)
    }
}

/// One model input of this text and its share of the decision.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct AiSignal {
    /// Machine name (e.g. `commas_per_sentence`, `pat_evidence`).
    pub key: String,
    /// Turkish display name.
    pub name: String,
    /// Value in this text.
    pub value: f64,
    /// Average value in AI and in human training texts.
    pub ai_mean: f64,
    pub human_mean: f64,
    /// Path contribution to the raw model score: positive pushes towards AI.
    pub contribution: f64,
}

/// Where a mined AI pattern was found.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum PatternKind {
    /// At the start of the text ("Elbette").
    Opener,
    /// At the end of the text ("umarım yardımcı olur").
    Closer,
    /// At the start of a sentence ("Bunun yanı sıra").
    SentenceStart,
    /// Anywhere ("önemli bir rol").
    Phrase,
}

impl PatternKind {
    /// Turkish label.
    pub fn label_tr(self) -> &'static str {
        match self {
            Self::Opener => "giriş",
            Self::Closer => "kapanış",
            Self::SentenceStart => "cümle başı",
            Self::Phrase => "kalıp ifade",
        }
    }
}

impl From<model::PatternPlace> for PatternKind {
    fn from(p: model::PatternPlace) -> Self {
        match p {
            model::PatternPlace::Opener => Self::Opener,
            model::PatternPlace::Closer => Self::Closer,
            model::PatternPlace::SentStart => Self::SentenceStart,
            model::PatternPlace::Phrase => Self::Phrase,
        }
    }
}

/// A mined AI pattern found in the text.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct AiPattern {
    pub kind: PatternKind,
    pub pattern: String,
    /// Share of AI answers / human texts containing it.
    pub ai_rate: f64,
    pub human_rate: f64,
}

/// Result of the AI-text detector for one text.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct AiDetection {
    pub model_version: String,
    pub verdict: AiVerdict,
    /// Calibrated AI probability (0–1); `None` when no decision is made.
    pub ai_probability: Option<f64>,
    /// Flag threshold and human cut-off of the probability.
    pub threshold: f64,
    pub uncertain_low: f64,
    /// Words (masked numbers, names, URLs and e-mails excluded), how many of them are
    /// different, and the minimum of each for a decision.
    pub n_words: usize,
    pub n_distinct_words: usize,
    pub min_words: usize,
    pub min_distinct_words: usize,
    /// Text type the model is unreliable on, if recognised.
    pub scope: Option<ScopeWarning>,
    /// The inputs that moved the decision most, largest absolute contribution first (empty
    /// without a decision).
    pub signals: Vec<AiSignal>,
    /// Mined AI patterns found, most AI-typical first.
    pub patterns: Vec<AiPattern>,
    /// Turkish "why AI" report (markdown).
    pub report: String,
}

impl AiDetection {
    pub fn is_ai(&self) -> bool {
        self.verdict == AiVerdict::Ai
    }
}

/// Where each model input comes from.
#[derive(Clone, Copy)]
enum Source {
    Content(usize),
    Pattern(usize),
    Token(usize),
}

const PATTERN_INPUTS: [&str; 5] = [
    "pat_opener",
    "pat_closer",
    "pat_sent_start_n",
    "pat_phrase_n",
    "pat_evidence",
];
const TOKEN_INPUTS: [&str; 2] = ["wordlm_llr_mean", "wordlm_ai_share"];

static SOURCES: LazyLock<Vec<Source>> = LazyLock::new(|| {
    MODEL
        .features
        .iter()
        .map(|f| {
            let key = f.key.as_str();
            if let Some(i) = FEATURE_NAMES.iter().position(|n| *n == key) {
                Source::Content(i)
            } else if let Some(i) = PATTERN_INPUTS.iter().position(|n| *n == key) {
                Source::Pattern(i)
            } else if let Some(i) = TOKEN_INPUTS.iter().position(|n| *n == key) {
                Source::Token(i)
            } else {
                panic!("embedded model input {key:?} is unknown to this build")
            }
        })
        .collect()
});

/// Model inputs of a text, with what the explanation needs.
struct Inputs {
    /// Raw values in model input order.
    x: Vec<f64>,
    hits: Vec<&'static PatternSpec>,
    n_words: usize,
    n_types: usize,
}

fn inputs(text: &str) -> Inputs {
    let content = content_features(&preprocess(text));
    let content_values = content.to_array();
    let hits = found_patterns(text);
    let pat = pattern_features(&hits);
    let tok = transition_features(text);
    let x = SOURCES
        .iter()
        .map(|s| match *s {
            Source::Content(i) => content_values[i],
            Source::Pattern(i) => pat[i],
            Source::Token(i) => tok[i],
        })
        .collect();
    Inputs {
        x,
        hits,
        n_words: content.n_words,
        n_types: content.n_types,
    }
}

/// Keys of the model inputs, for tests that check names used elsewhere.
#[cfg(test)]
pub(super) fn model_input_keys() -> Vec<&'static str> {
    MODEL.features.iter().map(|f| f.key.as_str()).collect()
}

/// Calibrated AI probability of a text (no decision rules, no explanation).
fn probability(text: &str) -> f64 {
    let z = MODEL.standardize(&inputs(text).x);
    MODEL.probability(MODEL.raw_score(&z))
}

/// Runs the detector on a text.
pub(super) fn detect(text: &str) -> AiDetection {
    let m = &*MODEL;
    let input = inputs(text);
    let scope = scope::out_of_scope(text);
    let z = m.standardize(&input.x);
    let p = m.probability(m.raw_score(&z));
    let verdict = if scope.as_ref().is_some_and(|s| s.kind == ScopeKind::Poem) {
        AiVerdict::OutOfScope
    } else if input.n_words < m.min_words || input.n_types < MIN_DISTINCT_WORDS {
        AiVerdict::TooShort
    } else if p >= m.threshold {
        AiVerdict::Ai
    } else if p < m.uncertain_low {
        AiVerdict::Human
    } else {
        AiVerdict::Uncertain
    };
    let decided = verdict.is_decided();
    let mut detection = AiDetection {
        model_version: m.model_version.clone(),
        verdict,
        ai_probability: decided.then_some(p),
        threshold: m.threshold,
        uncertain_low: m.uncertain_low,
        n_words: input.n_words,
        n_distinct_words: input.n_types,
        min_words: m.min_words,
        min_distinct_words: MIN_DISTINCT_WORDS,
        scope,
        signals: if decided {
            signals(&input.x, &m.contributions(&z))
        } else {
            Vec::new()
        },
        patterns: if decided {
            found(input.hits)
        } else {
            Vec::new()
        },
        report: String::new(),
    };
    detection.report = report(&detection);
    detection
}

fn signals(x: &[f64], contributions: &[f64]) -> Vec<AiSignal> {
    let mut order: Vec<usize> = (0..N_INPUTS).collect();
    order.sort_by(|&a, &b| contributions[b].abs().total_cmp(&contributions[a].abs()));
    order
        .into_iter()
        .take(MAX_SIGNALS)
        .map(|i| {
            let f = &MODEL.features[i];
            AiSignal {
                key: f.key.clone(),
                name: f.name.clone(),
                value: x[i],
                ai_mean: f.ai_mean,
                human_mean: f.human_mean,
                contribution: contributions[i],
            }
        })
        .collect()
}

fn found(mut hits: Vec<&'static PatternSpec>) -> Vec<AiPattern> {
    hits.sort_by(|a, b| b.ai_rate.total_cmp(&a.ai_rate));
    let mut seen = ahash::AHashSet::new();
    hits.into_iter()
        .filter(|p| seen.insert(p.pattern.as_str()))
        .map(|p| AiPattern {
            kind: p.kind.into(),
            pattern: p.pattern.clone(),
            ai_rate: p.ai_rate,
            human_rate: p.human_rate,
        })
        .collect()
}

/// A sliding section of a long text, scored on its own.
pub(super) struct Section<'a> {
    /// 1-based positions of its first and last whitespace-separated word.
    pub start_word: usize,
    pub end_word: usize,
    pub text: &'a str,
    pub ai_probability: f64,
}

/// Sliding 80-word sections (step 40) of a text of at least 120 words, each scored on its
/// own: one extra model run per section, so only computed where shown.
pub(super) fn sections(text: &str) -> Vec<Section<'_>> {
    let spans: Vec<(usize, usize)> = text
        .split_whitespace()
        .map(|w| {
            let start = w.as_ptr() as usize - text.as_ptr() as usize;
            (start, start + w.len())
        })
        .collect();
    let n = spans.len();
    if n < SECTION_MIN_WORDS {
        return Vec::new();
    }
    let mut starts: Vec<usize> = (0..=n - SECTION_WORDS).step_by(SECTION_STEP).collect();
    if starts.last() != Some(&(n - SECTION_WORDS)) {
        starts.push(n - SECTION_WORDS);
    }
    starts
        .into_iter()
        .map(|a| {
            let b = a + SECTION_WORDS;
            let piece = &text[spans[a].0..spans[b - 1].1];
            Section {
                start_word: a + 1,
                end_word: b,
                text: piece,
                ai_probability: probability(piece),
            }
        })
        .collect()
}

/// A probability as a Turkish percentage ("%7,5", "%93", "%99'dan fazla").
pub(super) fn pct(x: f64) -> String {
    let v = x * 100.0;
    if v > 0.0 && v < 0.1 {
        "%0,1'den az".into()
    } else if v > 99.5 && v < 100.0 {
        "%99'dan fazla".into()
    } else if v >= 10.0 || v == 0.0 {
        format!("%{v:.0}")
    } else {
        format!("%{v:.1}").replace('.', ",")
    }
}

fn num(x: f64) -> String {
    let s = if x.abs() >= 100.0 {
        format!("{x:.0}")
    } else if x.abs() >= 10.0 {
        format!("{x:.1}")
    } else {
        format!("{x:.2}")
    };
    s.replace('.', ",")
}

/// Turkish description of every model input, by key.
static DESCRIPTIONS: LazyLock<ahash::AHashMap<&'static str, &'static str>> = LazyLock::new(|| {
    MODEL
        .features
        .iter()
        .map(|f| (f.key.as_str(), f.desc.as_str()))
        .collect()
});

/// One sentence about an input: its value here and the typical AI / human values.
pub(super) fn signal_sentence(s: &AiSignal) -> String {
    let desc = DESCRIPTIONS
        .get(s.key.as_str())
        .map_or("", |d| d.trim_end_matches('.'));
    format!(
        "**{}**: bu metinde {}; AI metinlerinde ortalama {}, insan metinlerinde {}. ({desc})",
        s.name,
        num(s.value),
        num(s.ai_mean),
        num(s.human_mean),
    )
}

/// Inputs pushing towards AI, strongest first.
pub(super) fn ai_signals(d: &AiDetection) -> impl Iterator<Item = &AiSignal> {
    d.signals.iter().filter(|s| s.contribution > 0.0)
}

/// Turkish markdown "why AI" report.
fn report(d: &AiDetection) -> String {
    let mut out = String::from("# AI tespit raporu\n\n");
    match d.ai_probability {
        Some(p) => {
            let _ = writeln!(
                out,
                "**Sonuç:** {} — AI olasılığı {} (AI demek için eşik {}, {} altı insan).\n",
                d.verdict.label_tr(),
                pct(p),
                pct(d.threshold),
                pct(d.uncertain_low)
            );
        }
        None => {
            let _ = writeln!(
                out,
                "**Sonuç:** {} — karar verilmedi.\n",
                d.verdict.label_tr()
            );
        }
    }
    if d.verdict == AiVerdict::TooShort {
        let _ = writeln!(
            out,
            "Metinde {} kelime ({} farklı) var; model en az {} kelime ve {} farklı kelimede karar \
             veriyor (sayılar, isimler ve adresler sayılmaz).\n",
            d.n_words, d.n_distinct_words, d.min_words, d.min_distinct_words
        );
    }
    if let Some(s) = &d.scope {
        let _ = writeln!(out, "⚠ {}\n", s.message);
    }
    let ai: Vec<&AiSignal> = ai_signals(d).take(REPORT_AI_SIGNALS).collect();
    if !ai.is_empty() {
        out.push_str(if d.is_ai() {
            "## Neden AI'a benziyor?\n\n"
        } else {
            "## AI'a benzeyen yanlar\n\n"
        });
        for s in ai {
            let _ = writeln!(out, "- {}", signal_sentence(s));
        }
        out.push('\n');
    }
    if !d.patterns.is_empty() {
        out.push_str("## Bulunan AI kalıpları\n\n");
        for p in d.patterns.iter().take(REPORT_PATTERNS) {
            let _ = writeln!(
                out,
                "- «{}» ({}): AI cevaplarında {}, insan metinlerinde {} oranında geçiyor.",
                p.pattern,
                p.kind.label_tr(),
                pct(p.ai_rate),
                pct(p.human_rate)
            );
        }
        out.push('\n');
    }
    let human: Vec<&AiSignal> = d
        .signals
        .iter()
        .filter(|s| s.contribution < 0.0)
        .take(REPORT_HUMAN_SIGNALS)
        .collect();
    if !human.is_empty() {
        out.push_str("## İnsana benzeyen yanlar\n\n");
        for s in human {
            let _ = writeln!(out, "- {}", signal_sentence(s));
        }
        out.push('\n');
    }
    out.push_str(
        "_Bu bir olasılıktır, kanıt değildir. Model OpenAI ve Claude metinleriyle eğitildi; \
         hiç görmediği yeni modellerde daha zayıftır._\n",
    );
    out
}

