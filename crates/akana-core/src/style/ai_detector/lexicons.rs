/// Placeholders in original and Turkish-lower-cased spelling.
pub(super) static MASKS: LazyLock<Vec<String>> = LazyLock::new(|| {
    let mut v = Vec::new();
    for m in [
        MASK_YEAR,
        MASK_NUMBER,
        MASK_PROPER_NOUN,
        MASK_URL,
        MASK_EMAIL,
    ] {
        v.push(m.to_string());
        let lower = to_turkish_lower(m);
        if lower != m {
            v.push(lower);
        }
    }
    v
});
