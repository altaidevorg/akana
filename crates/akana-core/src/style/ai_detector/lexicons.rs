/// The cliché categories found to be high-precision in the detector's training data
/// (≥ 5% of AI texts vs ≤ 0.4% of human texts).
/// Cheap gate in front of [`super::cliches::count`] (Unicode regexes, the costliest part of
/// the extraction). The gate is a *necessary* condition for any match, checked on the
/// word-token stream, so the count is unchanged:
/// - adjective + `bir` + noun trigram (`rol_oynamaktadir`, `onem_tasimaktadir`,
///   `oneme_sahiptir`, `vazgecilmez`, `sifat_bir_isim_enflasyonu`);
/// - a single anchor word (`göz ardı edilmemelidir`, `unutulmamalıdır ki`,
///   `özetlemek gerekirse`, `… ile sınırlı kalmayıp`);
/// - co-occurring anchors (`sadece … değil, aynı zamanda / bununla birlikte`,
///   `… olmakla birlikte, … niteliğini taşımaktadır`, `… ötesinde, … boyutu`).
///
/// Anchors are written with `ı` folded to `i` and compared the same way, because the
/// regexes' `(?i)` treats ASCII `I` as `i`. **Keep in sync with [`super::cliches`]**; the
/// test `cliche_gate_is_a_necessary_condition` checks every pattern.
#[derive(Default)]
pub(super) struct ClicheGate<'a> {
    prev2: &'a str,
    prev1: &'a str,
    hit: bool,
    flags: u8,
}

const GATE_ADJ: &[&str] = &[
    "kritik",
    "önemli",
    "büyük",
    "belirleyici",
    "temel",
    "hayati",
    "özel",
    "merkezi",
    "stratejik",
    "kapsamli",
    "başarili",
    "etkili",
    "güçlü",
    "vazgeçilmez",
];
const GATE_NOUN: &[&str] = &[
    "adim",
    "rol",
    "aşama",
    "süreç",
    "unsur",
    "faktör",
    "örnek",
    "çalişma",
    "katki",
    "dönüm",
    "önem",
    "öneme",
    "parça",
    "hale",
    "parçasidir",
    "öğe",
];
const GATE_SINGLE: &[&str] = &["edilmemelidir", "unutulmamalidir", "özetlemek", "kalmayip"];
/// `(anchor, flag bit)` for anchors that only count together.
const GATE_FLAGS: &[(&str, u8)] = &[
    ("sadece", 1),
    ("yalnizca", 1),
    ("salt", 1),
    ("değil", 2),
    ("zamanda", 4),
    ("bununla", 4),
    ("olmakla", 8),
    ("niteliğini", 16),
    ("ötesinde", 32),
    ("boyutu", 64),
];

/// `word == anchor` with `ı` read as `i`.
fn eq_fold_i(word: &str, anchor: &str) -> bool {
    word.chars()
        .map(|c| if c == 'ı' { 'i' } else { c })
        .eq(anchor.chars())
}

fn any_fold_i(word: &str, anchors: &[&str]) -> bool {
    anchors.iter().any(|a| eq_fold_i(word, a))
}

impl<'a> ClicheGate<'a> {
    pub(super) fn push(&mut self, w: &'a str) {
        if !self.hit {
            let trigram = eq_fold_i(self.prev1, "bir")
                && any_fold_i(w, GATE_NOUN)
                && any_fold_i(self.prev2, GATE_ADJ);
            self.hit = trigram || any_fold_i(w, GATE_SINGLE);
            for (anchor, bit) in GATE_FLAGS {
                if eq_fold_i(w, anchor) {
                    self.flags |= bit;
                }
            }
        }
        self.prev2 = self.prev1;
        self.prev1 = w;
    }

    pub(super) fn open(&self) -> bool {
        let all = |m: u8| self.flags & m == m;
        self.hit || all(1 | 2 | 4) || all(8 | 16) || all(32 | 64)
    }
}

